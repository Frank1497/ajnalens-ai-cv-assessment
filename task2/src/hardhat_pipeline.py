# onnxruntime-gpu's CUDAExecutionProvider dlopens NVIDIA shared libs (libcublasLt.so.12, libcufft.so.11, ...)
# that pip installs as separate 'nvidia-*' wheel packages scattered across site-packages/nvidia/*/lib — none
# of those dirs are on the loader path by default, so CUDA EP silently falls back to CPU. Fix once, here.
def _fix_onnxruntime_cuda_ld_path() -> None:
    import glob
    import site

    lib_dirs = [d for sp in site.getsitepackages() for d in glob.glob(os.path.join(sp, "nvidia", "*", "lib"))]
    if lib_dirs:
        os.environ["LD_LIBRARY_PATH"] = os.pathsep.join(lib_dirs + [os.environ.get("LD_LIBRARY_PATH", "")])


