def _draw_failure(rec: dict, names: list[str]):
    import cv2

    image = cv2.imread(rec["img_path"])
    if image is None:
        raise RuntimeError(f"could not read {rec['img_path']}")
    height, width = image.shape[:2]
    if (width, height) != (rec["width"], rec["height"]):
        raise RuntimeError(f"size mismatch for {rec['img']}: file {width}x{height}, "
                           f"record {rec['width']}x{rec['height']}")
    zoom = max(1.0, FAIL_DISPLAY_LONG_SIDE / max(width, height))
    if zoom > 1:
        image = cv2.resize(image, (int(round(width * zoom)), int(round(height * zoom))),
                           interpolation=cv2.INTER_CUBIC)
    height, width = image.shape[:2]
    scale = max(0.7, width / 1400)
    thickness = max(2, int(round(width / 450)))
    font = cv2.FONT_HERSHEY_SIMPLEX

    def text(box, label, color):
        x1, y1, x2, y2 = [int(round(v * zoom)) for v in box]
        x1, y1 = max(0, x1), max(0, y1)
        x2, y2 = min(width - 1, x2), min(height - 1, y2)
        cv2.rectangle(image, (x1, y1), (x2, y2), color, thickness)
        (tw, th), _ = cv2.getTextSize(label, font, scale, thickness)
        ty = y1 - 6 if y1 - th - 8 > 0 else min(height - 2, y2 + th + 8)
        cv2.putText(image, label, (x1, ty), font, scale, color, thickness, cv2.LINE_AA)

    for tp in rec["true_pos"]:
        text(tp["xyxy"], f"TP {names[tp['cls']]} {tp['conf']:.2f}", (255, 80, 0))
    for fn in rec["false_negs"]:
        text(fn["xyxy"], f"missed {names[fn['cls']]}", (0, 180, 0))
    for fp in rec["false_pos"]:
        text(fp["xyxy"], f"FP {names[fp['cls']]} {fp['conf']:.2f}", (0, 0, 255))
    for swap in rec["swaps"]:
        text(swap["gt_xyxy"], f"GT {names[swap['gt_cls']]}", (0, 140, 255))
        text(swap["xyxy"], f"pred {names[swap['pred_cls']]} {swap['conf']:.2f}", (180, 0, 180))
    return image


def _public_case(rec: dict, names: list[str]) -> dict:
    def box(item, key="xyxy"):
        return [round(float(v), 1) for v in item[key]]

    return {
        "img": rec["img"],
        "img_path": rec["img_path"],
        "width": rec["width"],
        "height": rec["height"],
        "category": rec["category"],
        "reason": rec.get("reason", ""),
        "true_pos": [{"cls": names[t["cls"]], "conf": round(t["conf"], 3), "xyxy": box(t)}
                     for t in rec["true_pos"]],
        "false_pos": [{"cls": names[p["cls"]], "conf": round(p["conf"], 3), "xyxy": box(p)}
                      for p in rec["false_pos"]],
        "false_negs": [{"cls": names[f["cls"]], "xyxy": box(f),
                        "short_side_px": round(f["short_side"], 1),
                        "best_same_class_conf": round(f["best_same_class_conf"], 3),
                        "best_same_class_iou": round(f["best_same_class_iou"], 3)}
                       for f in rec["false_negs"]],
        "swaps": [{"gt_cls": names[s["gt_cls"]], "pred_cls": names[s["pred_cls"]],
                   "conf": round(s["conf"], 3), "iou": round(s["iou"], 3),
                   "xyxy": box(s), "gt_xyxy": box(s, "gt_xyxy")}
                  for s in rec["swaps"]],
    }


