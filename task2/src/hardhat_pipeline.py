    out_dir.mkdir(parents=True)
    cases = []
    for i, rec in enumerate(chosen, 1):
        image = _draw_failure(rec, names)
        dest = out_dir / f"failure_{i}_{rec['img']}"
        cv2.imwrite(str(dest), image, [cv2.IMWRITE_JPEG_QUALITY, 90])
        cases.append(_public_case(rec, names))
        print("wrote", dest)
    report = {"model": str(best_weights(a.run)), "conf": a.conf, "match_iou": FAIL_IOU,
              "coordinate_space": "original image pixels (label x image width/height, prediction xyxy)",
              "legend": "blue=true positive, red=false positive, green=missed ground truth, "
                        "orange/purple=class mix-up",
              "cases": cases}
    (FAIL_DIR / "failure_cases.json").write_text(json.dumps(report, indent=2))
    md = ["# Task 2 failure cases", "",
          f"Model `{best_weights(a.run).name}` from `{a.run}`. "
          f"Detections kept at conf ≥ {a.conf}, matched to ground truth at IoU {FAIL_IOU} "
          "in the original image's pixel frame.",
          "",
          f"The JPEGs are enlarged so the long side is {FAIL_DISPLAY_LONG_SIDE} px. "
          "The test photos themselves are about 400–500 px wide. "
          "Boxes in `failure_cases.json` are still original-image pixels.",
          "",
          "Blue is a true positive, red a false positive, green a missed ground-truth box, "
          "orange/purple a class mix-up.",
          ""]
    for i, case in enumerate(cases, 1):
        md.append(f"{i}. `failure_{i}_{case['img']}` — {case['reason']}")
    (out_dir / "README.md").write_text("\n".join(md) + "\n")
    print(f"wrote {FAIL_DIR / 'failure_cases.json'}")


