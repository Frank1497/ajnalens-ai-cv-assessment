def cmd_generalize(a: argparse.Namespace) -> None:
    from ultralytics import YOLO

    src = Path(a.src).resolve()
    dst = EXTRAS / "generalization_test"
    dst.mkdir(parents=True, exist_ok=True)
    _ultralytics_home()
    model = YOLO(str(best_weights(a.run)))
    report = {}
    for p in sorted(src.iterdir()):
        if p.suffix.lower() not in {".jpg", ".jpeg", ".png", ".webp"}:
            continue
        r = model.predict(str(p), imgsz=640, conf=a.conf, device=0, verbose=False)[0]
        r.save(filename=str(dst / f"pred_{p.stem}.jpg"), line_width=2)
        report[p.name] = [{"cls": r.names[int(c)], "conf": round(float(s), 3),
                           "xyxy": [round(float(v), 1) for v in b]}
                          for c, s, b in zip(r.boxes.cls, r.boxes.conf, r.boxes.xyxy)]
    (dst / "detections.json").write_text(json.dumps(report, indent=2))
    for k, v in report.items():
        counts = {}
        for d in v:
            counts[d["cls"]] = counts.get(d["cls"], 0) + 1
        print(k, counts, [round(d["conf"], 2) for d in v])


