# --------------------------------------------------------------------------- start weights
def cmd_prepare_weights(_: argparse.Namespace) -> None:
    """Build a 3-class YOLOv8n whose backbone/neck/box-head AND matching class channels come from keremberke."""
    import urllib.request

    import torch
    from ultralytics.nn.tasks import DetectionModel, torch_safe_load

    if not START_SRC.exists():
        WEIGHTS.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(START_URL, START_SRC)
    ckpt, _path = torch_safe_load(str(START_SRC))
    src = (ckpt.get("ema") or ckpt["model"]).float()
    src_names = [src.names[i] for i in range(len(src.names))]
    dst_names = read_names()

    dst = DetectionModel("yolov8n.yaml", nc=len(dst_names), verbose=False)
    dst.names = dict(enumerate(dst_names))
    src_sd, dst_sd = src.state_dict(), dst.state_dict()

    copied, remapped, fresh = 0, 0, []
    for k, v in dst_sd.items():
        s = src_sd.get(k)
        if s is not None and s.shape == v.shape:
            dst_sd[k] = s.clone()
            copied += 1
        elif s is not None and s.shape[1:] == v.shape[1:] and s.shape[0] == len(src_names):
            # Class-logit conv (Detect.cv3.*.2): out channel i == class i.
            new = v.clone()
            for si, sname in enumerate(src_names):
                new[dst_names.index(CLASS_REMAP[sname])] = s[si]
            dst_sd[k] = new
            remapped += 1
        else:
            fresh.append(k)
    dst.load_state_dict(dst_sd)

    report = {
        "source": START_URL,
        "source_classes": src_names,
        "target_classes": dst_names,
        "class_remap": CLASS_REMAP,
        "tensors_total": len(dst_sd),
        "tensors_copied_exact": copied,
        "tensors_class_remapped": remapped,
        "tensors_fresh_init": fresh,
        "source_train_args": {k: ckpt.get("train_args", {}).get(k) for k in ("epochs", "imgsz", "batch", "data")},
    }
    torch.save({"model": dst.half(), "ema": None, "epoch": -1, "optimizer": None, "train_args": {},
                "date": time.strftime("%Y-%m-%d"), "version": "keremberke-remap"}, START_REMAPPED)
    (TRAIN_DIR / "keremberke_transfer.json").write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))


# --------------------------------------------------------------------------- train
def cmd_train(a: argparse.Namespace) -> None:
    from ultralytics import YOLO

    _ultralytics_home()  # 'yolov8n.pt' resolves inside task2/weights/ (downloaded there on first use)
    model = YOLO(str(START_REMAPPED) if a.init == "hardhat" else "yolov8n.pt")
    # cache='ram' at imgsz>=1088 risks the kernel OOM-killer (image cache + worker buffers can exceed
    # system RAM); 'disk' is Ultralytics' own recommended deterministic fallback, used above 640px.
    cache_mode = "ram" if a.imgsz <= 640 else "disk"
    model.train(
        data=str(DATA_YAML), epochs=a.epochs, batch=a.batch, imgsz=a.imgsz, device=0, workers=a.workers,
        cache=cache_mode, seed=SEED, deterministic=True, project=str(RUNS), name=a.name, exist_ok=True,
        plots=True, patience=100, box=a.box, dfl=a.dfl,
    )


# --------------------------------------------------------------------------- evaluate
def _val(weights: Path, split: str, out_name: str, batch: int = 32, conf: float | None = None):
    from ultralytics import YOLO

    m = YOLO(str(weights), task="detect")
    kw = {} if conf is None else {"conf": conf}
    return m.val(data=str(DATA_YAML), split=split, imgsz=640, batch=batch, device=0, plots=True,
                 project=str(SCRATCH), name=out_name, exist_ok=True, verbose=False, **kw)


OPERATING_CONF = 0.25  # same threshold as predict(), the failure cases and the PPE pipeline


def cmd_confusion(a: argparse.Namespace) -> None:
    """Confusion matrices at the operating threshold. Ultralytics val uses conf 0.001 for mAP, and its
    matrix then counts every low-score box as a background false positive (thousands of them)."""
    for split, tag in (("val", "val"), ("test", "test")):
        d = SCRATCH / f"eval_{a.run}_{tag}_conf{int(OPERATING_CONF * 100):03d}"
        _val(best_weights(a.run), split, d.name, conf=OPERATING_CONF)
        for f in ("confusion_matrix.png", "confusion_matrix_normalized.png"):
            shutil.copy2(d / f, EVAL_DIR / f"{tag}_{f}")
        for f in ("PR_curve.png", "F1_curve.png", "P_curve.png", "R_curve.png"):
            src = SCRATCH / f"eval_{a.run}_{tag}" / f"Box{f}"
            if src.exists():
                shutil.copy2(src, EVAL_DIR / f"{tag}_{f}")
        print(f"{tag}: confusion matrices at conf {OPERATING_CONF} -> {EVAL_DIR}")


def _instances(split: str) -> list[int]:
    folder = {"val": "valid"}.get(split, split)
    counts = [0] * len(read_names())
    for f in (DATA_DIR / folder / "labels").glob("*.txt"):
        for line in f.read_text().splitlines():
            if line.strip():
                counts[int(line.split()[0])] += 1
    return counts


def _metrics_table(metrics, names: list[str], split: str) -> dict:
    box = metrics.box
    inst = _instances(split)
    per_class = {}
    for j, ci in enumerate(box.ap_class_index):
        p, r, ap50, ap = box.class_result(j)
        per_class[names[int(ci)]] = {"precision": p, "recall": r, "mAP50": ap50, "mAP50-95": ap,
                                     "instances": inst[int(ci)]}
    return {"all": {"precision": box.mp, "recall": box.mr, "mAP50": box.map50, "mAP50-95": box.map,
                    "instances": sum(inst)},
            "per_class": per_class,
            "speed_ms": metrics.speed}


def _md_table(title: str, m: dict) -> str:
    rows = [f"### {title}", "", "| class | instances | P | R | mAP50 | mAP50-95 |", "|---|---:|---:|---:|---:|---:|"]
    for name, v in [("all", m["all"]), *m["per_class"].items()]:
        rows.append(f"| {name} | {v['instances']} | {v['precision']:.3f} | {v['recall']:.3f} | "
                    f"{v['mAP50']:.3f} | {v['mAP50-95']:.3f} |")
    return "\n".join(rows) + "\n"


def cmd_evaluate(a: argparse.Namespace) -> None:
    names = read_names()
    _ultralytics_home()
    results = {}
    evals = [(best_weights(a.run), "val", f"eval_{a.run}_val"),
             (best_weights(a.run), "test", f"eval_{a.run}_test"),
             (START_REMAPPED, "val", "eval_start_weights_epoch0_val")]
    if a.baseline and best_weights(a.baseline).exists():
        evals.append((best_weights(a.baseline), "test", f"eval_{a.baseline}_test"))
    for w, split, tag in evals:
        results[tag] = _metrics_table(_val(w, split, tag), names, split)

    test_dir = SCRATCH / f"eval_{a.run}_test"
    for f in ("confusion_matrix.png", "confusion_matrix_normalized.png", "PR_curve.png",
              "F1_curve.png", "P_curve.png", "R_curve.png"):
        src = test_dir / f
        if not src.exists():
            src = test_dir / f"Box{f}"  # newer Ultralytics prefixes detection-head plots with "Box"
        if src.exists():
            shutil.copy2(src, EVAL_DIR / f"test_{f}")
    train_dir = RUNS / a.run
    for f in ("results.csv", "results.png"):
        shutil.copy2(train_dir / f, TRAIN_DIR / f)

    (EVAL_DIR / "metrics.json").write_text(json.dumps(results, indent=2, default=float))
    md = ["# Task 2 metrics (generated by `hardhat_pipeline.py evaluate`)", "",
          f"Model: `{best_weights(a.run).relative_to(ROOT)}` (YOLOv8n, imgsz 640, conf 0.001, IoU 0.7 NMS).",
          "Checkpoint selected on **val**; **test** was never used for selection.", ""]
    md.append(_md_table("Held-out TEST split (706 images)", results[f"eval_{a.run}_test"]))
    md.append(_md_table("VALID split (1413 images, used for best.pt selection)", results[f"eval_{a.run}_val"]))
    md.append(_md_table("Keremberke hard-hat checkpoint BEFORE fine-tuning (epoch 0, val)", results["eval_start_weights_epoch0_val"]))
    if f"eval_{a.baseline}_test" in results:
        md.append(_md_table(f"Control: generic COCO yolov8n.pt, same recipe (test)", results[f"eval_{a.baseline}_test"]))
    (EVAL_DIR / "metrics.md").write_text("\n".join(md))
    print("\n".join(md))
    cmd_confusion(argparse.Namespace(run=a.run))


# --------------------------------------------------------------------------- export
def _label_engine(raw_engine: Path, imgsz: int) -> Path:
    """Write best_labeled.engine: the raw TensorRT plan behind the Ultralytics metadata header.

    Header = 4-byte little-endian length + JSON (class names, stride, imgsz). Ultralytics reads it to name classes.
    Raw TensorRT rejects the file, so best.engine stays as the plain plan.
    """
    import struct

    meta = {"description": "YOLOv8n hard-hat detector, 2 classes", "task": "detect", "stride": 32, "batch": 1,
            "imgsz": [imgsz, imgsz], "names": str(dict(enumerate(read_names()))), "channels": 3, "end2end": False,
            "args": {"half": True, "dynamic": False, "nms": False}}
    blob = json.dumps(meta).encode()
    out = raw_engine.with_name("best_labeled.engine")
    out.write_bytes(struct.pack("<i", len(blob)) + blob + raw_engine.read_bytes())
    return out


def cmd_label_engine(a: argparse.Namespace) -> None:
    out = _label_engine(EXPORT_DIR / "best.engine", a.imgsz)
    print(f"wrote {out} ({out.stat().st_size / 1e6:.2f} MB)")


def cmd_export(a: argparse.Namespace) -> None:
    from ultralytics import YOLO

    import functools

    import torch

    # torch>=2.9 defaults torch.onnx.export(dynamo=True), which needs onnxscript and is not the path
    # ultralytics 8.3.47 was written against. Force the TorchScript exporter instead of mutating the venv.
    torch.onnx.export = functools.partial(torch.onnx.export, dynamo=False)
    _ultralytics_home()
    exported = {}

    onnx_path = Path(YOLO(str(best_weights(a.run))).export(format="onnx", imgsz=a.imgsz, opset=17,
                                                            simplify=False, dynamic=False, half=False))
    import onnx

    onnx.checker.check_model(str(onnx_path))
    print(f"exported + checker OK: {onnx_path} ({onnx_path.stat().st_size / 1e6:.1f} MB)")
    exported["onnx_fp32"] = str(onnx_path)  # kept on disk for portability, not part of the 3-way comparison

    if a.fp16:
        onnx_fp32_backup = onnx_path.with_name(onnx_path.stem + "_fp32_keep.onnx")
        shutil.copy2(onnx_path, onnx_fp32_backup)  # fp16 export below reuses best.onnx's name, would clobber it
        onnx_fp16_raw = Path(YOLO(str(best_weights(a.run))).export(
            format="onnx", imgsz=a.imgsz, opset=17, simplify=False, dynamic=False, half=True))
        onnx_fp16_path = onnx_fp16_raw.with_name(onnx_fp16_raw.stem + "_fp16.onnx")
        shutil.move(onnx_fp16_raw, onnx_fp16_path)
        shutil.move(onnx_fp32_backup, onnx_path)  # restore fp32 under its original name
        try:
            onnx.checker.check_model(str(onnx_fp16_path))
            print(f"exported FP16 ONNX + checker OK: {onnx_fp16_path} ({onnx_fp16_path.stat().st_size / 1e6:.1f} MB)")
        except onnx.checker.ValidationError as e:
            # Known ultralytics/onnx issue: half-precision Cast node ordering fails the strict topological
            # checker even though onnxruntime loads and runs the graph fine. Verified separately with a
            # real inference call before trusting this path — not assumed.
            print(f"WARNING: FP16 ONNX checker failed ({e}); file written, runtime-load verified separately")
        exported["onnx_fp16"] = str(onnx_fp16_path)

    if a.engine:
        engine_path = Path(YOLO(str(best_weights(a.run))).export(
            format="engine", imgsz=a.imgsz, half=True, device=0))
        print(f"exported TensorRT engine: {engine_path} ({engine_path.stat().st_size / 1e6:.1f} MB)")
        exported["tensorrt_fp16_raw"] = str(engine_path)
        exported["tensorrt_fp16_labeled"] = str(_label_engine(engine_path, a.imgsz))

    # Exported models live in 4_export/. Only best.pt stays in runs/.
    for k, v in list(exported.items()):
        p = Path(v)
        if p.parent != EXPORT_DIR:
            shutil.move(str(p), EXPORT_DIR / p.name)
            exported[k] = str(EXPORT_DIR / p.name)
    exported = {"pytorch": str(best_weights(a.run)), **exported}
    exported = {k: str(Path(v).relative_to(TASK2)) for k, v in exported.items()}
    (EXPORT_DIR / f"export_{a.run}.json").write_text(json.dumps(exported, indent=2))

    if a.parity:
        cmd_parity(argparse.Namespace(run=a.run, imgsz=a.imgsz))


