# Boxes are matched in the original image's pixel frame. An earlier pass multiplied normalised
# labels by 640 and drew that on the unresized frame, so true positives were labelled as misses.
FAIL_CONF = 0.25
FAIL_IOU = 0.5
FAIL_CACHE = SCRATCH / "failure_match_cache.json"
# Test JPEGs are ~400–500 px wide. The annotated copy is enlarged for reading;
# JSON boxes stay in the original pixel frame.
FAIL_DISPLAY_LONG_SIDE = 1600


def _match_detections(gt: list[dict], preds: list[dict], conf_thr: float, iou_thr: float):
    """Class-aware greedy match. Predictions below conf_thr are not drawn, but they are
    recorded on a miss so a below-threshold detection is not described as 'the model saw nothing'."""
    used_g: set[int] = set()
    used_p: set[int] = set()
    tps = []
    high = [i for i, p in enumerate(preds) if p["conf"] >= conf_thr]
    high.sort(key=lambda i: -preds[i]["conf"])
    for i in high:
        pred = preds[i]
        best_j, best_v = None, 0.0
        for j, g in enumerate(gt):
            if j in used_g or g["cls"] != pred["cls"]:
                continue
            overlap = _iou(pred["xyxy"], g["xyxy"])
            if overlap > best_v:
                best_v, best_j = overlap, j
        if best_j is not None and best_v >= iou_thr:
            used_g.add(best_j)
            used_p.add(i)
            tps.append({"cls": pred["cls"], "conf": pred["conf"], "xyxy": pred["xyxy"], "iou": best_v})
    swaps = []
    for i in high:
        if i in used_p:
            continue
        pred = preds[i]
        best_j, best_v = None, 0.0
        for j, g in enumerate(gt):
            if j in used_g:
                continue
            overlap = _iou(pred["xyxy"], g["xyxy"])
            if overlap > best_v:
                best_v, best_j = overlap, j
        if best_j is not None and best_v >= iou_thr and gt[best_j]["cls"] != pred["cls"]:
            used_g.add(best_j)
            used_p.add(i)
            swaps.append({"gt_cls": gt[best_j]["cls"], "pred_cls": pred["cls"], "conf": pred["conf"],
                          "iou": best_v, "xyxy": pred["xyxy"], "gt_xyxy": gt[best_j]["xyxy"]})
    fps = [{"cls": preds[i]["cls"], "conf": preds[i]["conf"], "xyxy": preds[i]["xyxy"]}
           for i in high if i not in used_p]
    fns = []
    for j, g in enumerate(gt):
        if j in used_g:
            continue
        best_conf, best_iou = 0.0, 0.0
        for pred in preds:
            if pred["cls"] != g["cls"]:
                continue
            overlap = _iou(pred["xyxy"], g["xyxy"])
            if overlap > best_iou:
                best_iou, best_conf = overlap, pred["conf"]
        fns.append({"cls": g["cls"], "xyxy": g["xyxy"], "short_side": _short_side(g["xyxy"]),
                    "best_same_class_iou": best_iou, "best_same_class_conf": best_conf})
    return tps, fps, fns, swaps


def _collect_failure_records(run: str, conf_thr: float) -> tuple[list[dict], list[str]]:
    from ultralytics import YOLO

    _ultralytics_home()
    names = read_names()
    weights = best_weights(run)
    paths = sorted((DATA_DIR / "test" / "images").glob("*.jpg"))
    model = YOLO(str(weights))
    records = []
    oob = 0
    n_boxes = 0
    # One predict() call over the whole list builds a single batch and exhausts the 16 GB GPU.
    chunk = 8
    path_strs = [str(p) for p in paths]
    for start in range(0, len(path_strs), chunk):
        for result in model.predict(path_strs[start:start + chunk], imgsz=640, conf=0.001, device=0,
                                    verbose=False):
            height, width = result.orig_shape
            preds = []
            if result.boxes is not None and len(result.boxes):
                for cls_id, score, box in zip(result.boxes.cls, result.boxes.conf, result.boxes.xyxy):
                    xyxy = [float(v) for v in box]
                    preds.append({"cls": int(cls_id), "conf": float(score), "xyxy": xyxy})
                    n_boxes += 1
                    x1, y1, x2, y2 = xyxy
                    if x2 < -5 or y2 < -5 or x1 > width + 5 or y1 > height + 5:
                        oob += 1
            image_path = Path(result.path)
            gt = _read_gt(DATA_DIR / "test" / "labels" / f"{image_path.stem}.txt", width, height)
            tps, fps, fns, swaps = _match_detections(gt, preds, conf_thr, FAIL_IOU)
            records.append({
                "img": image_path.name,
                "img_path": str(image_path),
                "width": width,
                "height": height,
                "true_pos": tps,
                "false_pos": fps,
                "false_negs": fns,
                "swaps": swaps,
            })
    if n_boxes and oob / n_boxes > 0.01:
        raise RuntimeError(f"{oob}/{n_boxes} predictions fall outside the original image")
    check = next(r for r in records if r["img"].startswith("005684_"))
    if check["false_negs"] or check["false_pos"] or len(check["true_pos"]) != 2:
        raise RuntimeError(
            "005684 coordinate check failed: the two helmet labels should both be true positives "
            f"at conf {conf_thr}, got tp={len(check['true_pos'])} fp={len(check['false_pos'])} "
            f"fn={len(check['false_negs'])}")
    print(f"matched {len(records)} test images, {n_boxes} boxes, {oob} outside the frame")
    return records, names


