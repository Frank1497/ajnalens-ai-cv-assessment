def _selection_latency(n: int = 100, warmup: int = 10) -> None:
    """PyTorch end-to-end predict ms for the 640 and 1088 models on the same first n test images. Cost side of the
    choice between runs D (1088) and E (640). Written to model_selection_latency.json."""
    import cv2
    import torch
    from ultralytics import YOLO

    imgs = [cv2.imread(str(p)) for p in sorted((DATA_DIR / "test" / "images").glob("*.jpg"))[:n]]
    out = {}
    for tag, run, sz in (("E_imgsz640", "imgsz640_box_dfl", 640),
                         ("D_imgsz1088", "imgsz1088_box_dfl", 1088)):
        m = YOLO(str(RUNS / run / "weights" / "best.pt"))
        ms = _timed(lambda x: m.predict(x, imgsz=sz, conf=OPERATING_CONF, verbose=False, device=0), warmup, imgs,
                    torch.cuda.synchronize)
        out[tag] = {"run": run, "imgsz": sz, "images": n, **{k: round(v, 2) for k, v in _summ(ms).items() if k != "n"}}
    (COMPARE_DIR / "model_selection_latency.json").write_text(json.dumps(out, indent=2))
    print(out)


def cmd_compare(_: argparse.Namespace) -> None:
    """Re-score every kept training run on the SAME 2-class test labels, at its own train imgsz and at 640."""
    from ultralytics import YOLO

    _ultralytics_home()
    rows = []
    for label, run, trained_at, note in SELECTION_RUNS:
        w = RUNS / run / "weights" / "best.pt"
        if not w.exists():
            continue
        for sz in sorted({trained_at, 640}):
            m = YOLO(str(w)).val(data=str(DATA_YAML), split="test", imgsz=sz, batch=32, device=0, plots=False,
                                 project=str(SCRATCH), name="compare_tmp", exist_ok=True, verbose=False)
            rows.append({"model": label, "run": run, "trained_imgsz": trained_at, "eval_imgsz": sz, "note": note,
                         "P": float(m.box.mp), "R": float(m.box.mr), "mAP50": float(m.box.map50),
                         "mAP50-95": float(m.box.map)})
            print(rows[-1])
    shutil.rmtree(SCRATCH / "compare_tmp", ignore_errors=True)
    (COMPARE_DIR / "model_selection.json").write_text(json.dumps(rows, indent=2))
    _selection_latency()
    md = ["| model | eval imgsz | P | R | mAP50 | mAP50-95 |", "|---|---:|---:|---:|---:|---:|"]
    for r in rows:
        md.append(f"| {r['model']} | {r['eval_imgsz']} | {r['P']:.3f} | {r['R']:.3f} | {r['mAP50']:.3f} | {r['mAP50-95']:.3f} |")
    (COMPARE_DIR / "model_selection.md").write_text("Test split (706 images, head+helmet only), batch 32, conf 0.001, IoU 0.7.\n\n" + "\n".join(md) + "\n")


def _plot_confusion_grid(rows: list[dict], path: Path) -> None:
    """One figure, same 3x3 layout and colour scale for every run. Cells show count and column percent."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    labels = ["head", "helmet", "background"]
    fig, axes = plt.subplots(2, 4, figsize=(24, 12.5))
    for ax, r in zip(axes.flat, rows):
        cm = np.array(r["matrix_pred_by_true"], dtype=float)
        col = cm / np.maximum(cm.sum(0, keepdims=True), 1)
        ax.imshow(col, cmap="Blues", vmin=0, vmax=1)
        for i in range(3):
            for j in range(3):
                if i == 2 and j == 2:
                    continue
                ax.text(j, i, f"{int(cm[i, j])}\n{col[i, j] * 100:.1f}%", ha="center", va="center", fontsize=13,
                        color="white" if col[i, j] > 0.5 else "black")
        ax.set_xticks(range(3), [f"true {x}" for x in labels], fontsize=10)
        ax.set_yticks(range(3), [f"pred {x}" for x in labels], fontsize=10)
        ax.set_title(f"{r['model'].split(',')[0]}  eval {r['eval_imgsz']}px\n({r['run']})\n"
                     f"mAP50 {r['mAP50']:.3f}   mAP50-95 {r['mAP50-95']:.3f}", fontsize=12)
    for ax in axes.flat[len(rows):]:
        ax.axis("off")
    fig.suptitle("Test split, 706 images, conf 0.25. Cell = count and share of its true-class column. "
                 "Columns sum to 100%.", fontsize=14)
    fig.tight_layout()
    fig.savefig(path, dpi=80)
    plt.close(fig)


def cmd_confusion_all(_: argparse.Namespace) -> None:
    """Confusion matrix of every run in SELECTION_RUNS on the test split, one procedure for all.

    conf 0.25 (operating threshold), IoU 0.7, classes restricted to head and helmet so the 3-class
    runs A and B are not charged for their `person` output, which the 2-class test labels do not contain.
    Matrix cells are [predicted, true]; the last row and column are background.
    """
