def _timed(fn, n_warm: int, inputs: list, sync=None) -> list[float]:
    for x in inputs[:n_warm]:
        fn(x)
    out = []
    for x in inputs:
        if sync:
            sync()
        t = time.perf_counter()
        fn(x)
        if sync:
            sync()
        out.append((time.perf_counter() - t) * 1e3)
    return out


def _summ(ms: list[float]) -> dict:
    ms = sorted(ms)
    mean = statistics.fmean(ms)
    return {"n": len(ms), "mean_ms": mean, "median_ms": statistics.median(ms),
            "p90_ms": ms[int(0.9 * (len(ms) - 1))], "fps": 1000.0 / mean}


def _iou(a: list[float], b: list[float]) -> float:
    x1, y1 = max(a[0], b[0]), max(a[1], b[1])
    x2, y2 = min(a[2], b[2]), min(a[3], b[3])
    inter = max(0.0, x2 - x1) * max(0.0, y2 - y1)
    if inter <= 0:
        return 0.0
    area_a = max(0.0, a[2] - a[0]) * max(0.0, a[3] - a[1])
    area_b = max(0.0, b[2] - b[0]) * max(0.0, b[3] - b[1])
    return inter / (area_a + area_b - inter)


def _read_gt(label_path: Path, width: int, height: int) -> list[dict]:
    if not label_path.exists():
        return []
    boxes = []
    for line in label_path.read_text().splitlines():
        if not line.strip():
            continue
        cls_s, cx, cy, bw, bh = line.split()
        cx, cy, bw, bh = float(cx), float(cy), float(bw), float(bh)
        boxes.append({
            "cls": int(cls_s),
            "xyxy": [(cx - bw / 2) * width, (cy - bh / 2) * height,
                     (cx + bw / 2) * width, (cy + bh / 2) * height],
        })
    return boxes


def _short_side(box: list[float]) -> float:
    return min(box[2] - box[0], box[3] - box[1])


